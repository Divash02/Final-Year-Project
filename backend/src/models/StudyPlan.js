import mongoose from "mongoose";

const StudyActivitySchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: true,
      trim: true,
      maxlength: 200,
    },
    description: {
      type: String,
      trim: true,
      maxlength: 1000,
      default: "",
    },
    type: {
      type: String,
      enum: [
        "ASSIGNMENT",
        "EXAM_PREPARATION",
        "READING",
        "PROJECT_WORK",
        "REVISION",
        "PRACTICE",
        "GROUP_STUDY",
        "PERSONAL",
      ],
      required: true,
    },
    sourceType: {
      type: String,
      enum: ["AUTO_GENERATED", "MANUAL", "LMS_SYNC", "EXAM_SYNC", "CALENDAR_SYNC"],
      default: "MANUAL",
    },
    sourceEntityType: {
      type: String,
      enum: ["ASSIGNMENT", "EXAM", "COURSE_WEEK", "ACADEMIC_CALENDAR", "PERSONAL"],
      default: null,
    },
    sourceEntityId: {
      type: mongoose.Schema.Types.ObjectId,
      default: null,
    },
    course: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Course",
      default: null,
    },
    startAt: {
      type: Date,
      required: true,
    },
    endAt: {
      type: Date,
      required: true,
    },
    estimatedDurationMinutes: {
      type: Number,
      min: 15,
      max: 480,
    },
    actualDurationMinutes: {
      type: Number,
      min: 0,
      max: 480,
      default: 0,
    },
    status: {
      type: String,
      enum: ["PLANNED", "IN_PROGRESS", "COMPLETED", "OVERDUE", "CANCELLED", "RESCHEDULED"],
      default: "PLANNED",
      index: true,
    },
    priority: {
      type: String,
      enum: ["LOW", "NORMAL", "HIGH", "URGENT"],
      default: "NORMAL",
    },
    completedAt: {
      type: Date,
      default: null,
    },
    isRecurring: {
      type: Boolean,
      default: false,
    },
    recurrencePattern: {
      frequency: { type: String, enum: ["DAILY", "WEEKLY", "BIWEEKLY", "MONTHLY"] },
      interval: { type: Number, min: 1, max: 4 },
      daysOfWeek: [{ type: Number, min: 0, max: 6 }],
      endDate: { type: Date },
    },
    tags: [{
      type: String,
      trim: true,
      maxlength: 30,
    }],
  },
  { _id: true }
);

const StudyPlanSchema = new mongoose.Schema(
  {
    student: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Student",
      required: true,
      index: true,
    },
    academicYear: {
      type: String,
      required: true,
      trim: true,
      maxlength: 20,
      index: true,
    },
    semester: {
      type: Number,
      min: 1,
      max: 12,
      required: true,
    },
    weekStartDate: {
      type: Date,
      required: true,
      index: true,
    },
    weekEndDate: {
      type: Date,
      required: true,
    },
    activities: [StudyActivitySchema],
    isActive: {
      type: Boolean,
      default: true,
    },
    isAutoGenerated: {
      type: Boolean,
      default: false,
    },
    lastSyncedAt: {
      type: Date,
      default: null,
    },
    totalPlannedMinutes: {
      type: Number,
      default: 0,
    },
    totalCompletedMinutes: {
      type: Number,
      default: 0,
    },
    completionRate: {
      type: Number,
      min: 0,
      max: 100,
      default: 0,
    },
  },
  { timestamps: true }
);

StudyPlanSchema.index({ student: 1, weekStartDate: 1 }, { unique: true });
StudyPlanSchema.index({ student: 1, isActive: 1, weekStartDate: -1 });
StudyPlanSchema.index({ student: 1, academicYear: 1, semester: 1 });

export const StudyActivity = StudyActivitySchema;
export const StudyPlan = mongoose.model("StudyPlan", StudyPlanSchema);